#!/usr/bin/env bash
# render.sh - turns the approved architecture map into native tool configuration. Read-only: it
# prints to stdout; the rules skill writes the output to the path the user approved.
#   bash render.sh <archunit-java|archunit-kotlin|archunit-properties|depcruise|importlinter> <env_file>
# The env file (.agents/rules/architecture.env) defines STYLE, LANG, BASE, LAYERS, FORBIDDEN, FREEZE:
#   LAYERS    lines  name|path_prefix|import_prefix|allowed_csv|role   (role: domainModels|domainServices|
#                    applicationServices|adapter|layer)
#   FORBIDDEN lines  layer|import_prefix
#   IGNORE_IMPORTS lines  importer -> imported   (import-linter's native baseline, brownfield)
# Exit 64 on bad usage, 65 on an env file without STYLE or LAYERS.
set -uo pipefail

target="${1:-}"; envf="${2:-}"
case "$target" in
  archunit-java | archunit-kotlin | archunit-properties | depcruise | importlinter) ;;
  *) echo "usage: render.sh <archunit-java|archunit-kotlin|archunit-properties|depcruise|importlinter> <env_file>" >&2; exit 64 ;;
esac
[ -f "$envf" ] || { echo "env file not found: $envf" >&2; exit 64; }

STYLE=""; LANG=""; BASE=""; LAYERS=""; FORBIDDEN=""; FREEZE=""; IGNORE_IMPORTS=""
orig_lang="${LANG-}"
eval "$(tr -d '\r' < "$envf")"
LANG="$orig_lang"
if [ -z "$STYLE" ] || [ -z "$LAYERS" ]; then
  echo "render.sh: $envf must define STYLE and LAYERS" >&2
  exit 65
fi

GEN="Generated by keel-harness from .agents/rules/architecture.env. Edit that file and re-run the rules skill; do not edit this by hand."

# --- parse the map into parallel arrays
n=0
while IFS='|' read -r a b c d e; do
  [ -n "$a" ] || continue
  L_NAME[n]="$a"; L_PATH[n]="$b"; L_IMP[n]="$c"; L_ALLOW[n]="$d"; L_ROLE[n]="${e:-layer}"
  n=$((n + 1))
done <<LIST
$LAYERS
LIST
f=0
while IFS='|' read -r a b; do
  [ -n "$a" ] || continue
  F_LAYER[f]="$a"; F_IMP[f]="$b"
  f=$((f + 1))
done <<LIST
$FORBIDDEN
LIST

idx_of() { # idx_of <layer name> -> index or empty
  local i=0
  while [ "$i" -lt "$n" ]; do [ "${L_NAME[$i]}" = "$1" ] && { echo "$i"; return; }; i=$((i + 1)); done
}
allows() { # allows <from idx> <to name> -> 0 when from may depend on to
  case ",${L_ALLOW[$1]}," in *",$2,"*) return 0 ;; esac
  return 1
}
ident() { printf '%s' "$1" | sed 's/[^A-Za-z0-9]/_/g'; }
regex_escape() { printf '%s' "$1" | sed 's/[.]/\\\\./g'; }

# =========================================================== ArchUnit
archunit_chain() { # prints the architecture chain (no trailing semicolon)
  local i role calls
  if [ "$STYLE" = hexagonal ]; then
    printf 'onionArchitecture()\n            .withOptionalLayers(true)'
    for role in domainModels domainServices applicationServices; do
      calls=""
      i=0
      while [ "$i" -lt "$n" ]; do
        if [ "${L_ROLE[$i]}" = "$role" ]; then calls="${calls}${calls:+, }\"${L_IMP[$i]}..\""; fi
        i=$((i + 1))
      done
      [ -n "$calls" ] && printf '\n            .%s(%s)' "$role" "$calls"
    done
    i=0
    while [ "$i" -lt "$n" ]; do
      case "${L_ROLE[$i]}" in
        domainModels | domainServices | applicationServices) ;;
        *) printf '\n            .adapter("%s", "%s..")' "${L_NAME[$i]}" "${L_IMP[$i]}" ;;
      esac
      i=$((i + 1))
    done
  else
    printf 'layeredArchitecture().consideringAllDependencies()'
    i=0
    while [ "$i" -lt "$n" ]; do
      printf '\n            .layer("%s").definedBy("%s..")' "${L_NAME[$i]}" "${L_IMP[$i]}"
      i=$((i + 1))
    done
    i=0
    while [ "$i" -lt "$n" ]; do
      calls=""
      local j=0
      while [ "$j" -lt "$n" ]; do
        if [ "$j" -ne "$i" ] && allows "$j" "${L_NAME[$i]}"; then calls="${calls}${calls:+, }\"${L_NAME[$j]}\""; fi
        j=$((j + 1))
      done
      if [ -n "$calls" ]; then printf '\n            .whereLayer("%s").mayOnlyBeAccessedByLayers(%s)' "${L_NAME[$i]}" "$calls"
      else printf '\n            .whereLayer("%s").mayNotBeAccessedByAnyLayer()' "${L_NAME[$i]}"; fi
      i=$((i + 1))
    done
  fi
}

archunit_forbidden() { # archunit_forbidden <index> -> the noClasses() expression
  local li
  li="$(idx_of "${F_LAYER[$1]}")"
  [ -n "$li" ] || return 1
  printf 'noClasses().that().resideInAPackage("%s..").should().dependOnClassesThat().resideInAPackage("%s..")' "${L_IMP[$li]}" "${F_IMP[$1]}"
}

# wrap_rule <expr> -> brownfield (FREEZE=1): frozen, so only new violations fail. Greenfield: allowed to
# check no classes, so a rule over a package that has no code yet does not fail ("failed to check any
# classes" is ArchUnit's default).
wrap_rule() {
  if [ "$FREEZE" = 1 ]; then printf 'FreezingArchRule.freeze(%s)' "$1"
  else printf '%s\n            .allowEmptyShould(true)' "$1"; fi
}

GUARD_WHY="ArchUnit must see this project's classes; when it imports none (e.g. a release older than the project's JDK), every other rule here passes without checking anything"

render_archunit() { # render_archunit java|kotlin
  local kt=0 semi=";" i expr
  [ "$1" = kotlin ] && { kt=1; semi=""; }
  if [ "$kt" -eq 1 ]; then
    printf 'package %s\n\n' "$BASE"
    printf 'import com.tngtech.archunit.core.importer.ImportOption\n'
    printf 'import com.tngtech.archunit.junit.AnalyzeClasses\nimport com.tngtech.archunit.junit.ArchTest\nimport com.tngtech.archunit.lang.ArchRule\n'
    [ "$FREEZE" = 1 ] && printf 'import com.tngtech.archunit.lang.syntax.ArchRuleDefinition.classes\n'
    [ "$f" -gt 0 ] && printf 'import com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses\n'
    if [ "$STYLE" = hexagonal ]; then printf 'import com.tngtech.archunit.library.Architectures.onionArchitecture\n'
    else printf 'import com.tngtech.archunit.library.Architectures.layeredArchitecture\n'; fi
    [ "$FREEZE" = 1 ] && printf 'import com.tngtech.archunit.library.freeze.FreezingArchRule\n'
    printf '\n// %s\n' "$GEN"
    printf '@AnalyzeClasses(packages = ["%s"], importOptions = [ImportOption.DoNotIncludeTests::class])\nclass ArchitectureTest {\n' "$BASE"
  else
    printf 'package %s;\n\n' "$BASE"
    printf 'import com.tngtech.archunit.core.importer.ImportOption;\n'
    printf 'import com.tngtech.archunit.junit.AnalyzeClasses;\nimport com.tngtech.archunit.junit.ArchTest;\nimport com.tngtech.archunit.lang.ArchRule;\n'
    [ "$FREEZE" = 1 ] && printf 'import com.tngtech.archunit.library.freeze.FreezingArchRule;\n'
    printf '\n'
    [ "$FREEZE" = 1 ] && printf 'import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.classes;\n'
    [ "$f" -gt 0 ] && printf 'import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses;\n'
    if [ "$STYLE" = hexagonal ]; then printf 'import static com.tngtech.archunit.library.Architectures.onionArchitecture;\n'
    else printf 'import static com.tngtech.archunit.library.Architectures.layeredArchitecture;\n'; fi
    printf '\n// %s\n' "$GEN"
    printf '@AnalyzeClasses(packages = "%s", importOptions = ImportOption.DoNotIncludeTests.class)\nclass ArchitectureTest {\n' "$BASE"
  fi
  # field: layers
  printf '\n    @ArchTest\n'
  if [ "$kt" -eq 1 ]; then printf '    @JvmField\n    val layers: ArchRule = '; else printf '    static final ArchRule layers = '; fi
  printf '%s%s\n' "$(wrap_rule "$(archunit_chain)")" "$semi"
  i=0
  while [ "$i" -lt "$f" ]; do
    expr="$(archunit_forbidden "$i")" || { i=$((i + 1)); continue; }
    printf '\n    @ArchTest\n'
    if [ "$kt" -eq 1 ]; then printf '    @JvmField\n    val %s_must_not_depend_on_%s: ArchRule = ' "$(ident "${F_LAYER[$i]}")" "$(ident "${F_IMP[$i]}")"
    else printf '    static final ArchRule %s_must_not_depend_on_%s = ' "$(ident "${F_LAYER[$i]}")" "$(ident "${F_IMP[$i]}")"; fi
    printf '%s%s\n' "$(wrap_rule "$expr")" "$semi"
    i=$((i + 1))
  done
  # Brownfield guard: fails when ArchUnit imported no class of the project at all.
  if [ "$FREEZE" = 1 ]; then
    printf '\n    @ArchTest\n'
    if [ "$kt" -eq 1 ]; then printf '    @JvmField\n    val classes_are_analysed: ArchRule = '; else printf '    static final ArchRule classes_are_analysed = '; fi
    printf 'classes().that().resideInAPackage("%s..").should().resideInAPackage("%s..")\n            .because("%s")%s\n' "$BASE" "$BASE" "$GUARD_WHY" "$semi"
  fi
  printf '}\n'
}

# =========================================================== dependency-cruiser
render_depcruise() {
  local i j li sep=""
  printf '// %s\n' "$GEN"
  printf '/** @type {import('"'"'dependency-cruiser'"'"').IConfiguration} */\nmodule.exports = {\n  forbidden: [\n'
  i=0
  while [ "$i" -lt "$n" ]; do
    j=0
    while [ "$j" -lt "$n" ]; do
      if [ "$i" -ne "$j" ] && ! allows "$i" "${L_NAME[$j]}"; then
        printf '%s    {\n      name: "%s-not-to-%s",\n' "$sep" "${L_NAME[$i]}" "${L_NAME[$j]}"
        printf '      comment: "Layer '"'"'%s'"'"' may not depend on layer '"'"'%s'"'"' (docs/architecture.md#architecture).",\n' "${L_NAME[$i]}" "${L_NAME[$j]}"
        printf '      severity: "error",\n      from: { path: "^%s/" },\n      to: { path: "^%s/" }\n    }' "$(regex_escape "${L_PATH[$i]}")" "$(regex_escape "${L_PATH[$j]}")"
        sep=$',\n'
      fi
      j=$((j + 1))
    done
    i=$((i + 1))
  done
  i=0
  while [ "$i" -lt "$f" ]; do
    li="$(idx_of "${F_LAYER[$i]}")"
    if [ -n "$li" ]; then
      printf '%s    {\n      name: "%s-no-%s",\n' "$sep" "${F_LAYER[$i]}" "$(ident "${F_IMP[$i]}")"
      printf '      comment: "Layer '"'"'%s'"'"' may not import %s (docs/architecture.md#architecture).",\n' "${F_LAYER[$i]}" "${F_IMP[$i]}"
      printf '      severity: "error",\n      from: { path: "^%s/" },\n      to: { path: "(^|/)node_modules/%s(/|$)" }\n    }' "$(regex_escape "${L_PATH[$li]}")" "$(regex_escape "${F_IMP[$i]}")"
      sep=$',\n'
    fi
    i=$((i + 1))
  done
  printf '\n  ],\n  options: { tsPreCompilationDeps: true }\n};\n'
}

# =========================================================== import-linter
# importlinter_ignores -> the ignore_imports block (empty when IGNORE_IMPORTS is empty)
importlinter_ignores() {
  [ -n "$IGNORE_IMPORTS" ] || return 0
  printf 'ignore_imports =\n'
  printf '%s\n' "$IGNORE_IMPORTS" | sed '/^[[:space:]]*$/d; s/^[[:space:]]*/    /'
  # A fixed baselined import leaves its entry unmatched; import-linter's default (error) would fail
  # the agent for improving the code. keel tightens the baseline later instead.
  printf 'unmatched_ignore_imports_alerting = warn\n'
}

render_importlinter() {
  local i j li pick remaining done_list order deps
  printf '# %s\n[importlinter]\nroot_package = %s\n' "$GEN" "${BASE%%.*}"
  [ "$f" -gt 0 ] && printf 'include_external_packages = True\n'
  # topological order: a layer nobody (remaining) depends on comes first
  done_list=","; order=""
  remaining=$n
  while [ "$remaining" -gt 0 ]; do
    pick=""
    i=0
    while [ "$i" -lt "$n" ]; do
      case "$done_list" in *",$i,"*) i=$((i + 1)); continue ;; esac
      deps=0; j=0
      while [ "$j" -lt "$n" ]; do
        case "$done_list" in *",$j,"*) ;; *) [ "$j" -ne "$i" ] && allows "$j" "${L_NAME[$i]}" && deps=1 ;; esac
        j=$((j + 1))
      done
      if [ "$deps" -eq 0 ]; then pick="$i"; break; fi
      i=$((i + 1))
    done
    if [ -z "$pick" ]; then # cycle: take the first remaining
      i=0; while [ "$i" -lt "$n" ]; do case "$done_list" in *",$i,"*) ;; *) pick="$i"; break ;; esac; i=$((i + 1)); done
    fi
    done_list="${done_list}${pick},"; order="${order} ${pick}"; remaining=$((remaining - 1))
  done
  printf '\n[importlinter:contract:layers]\nname = Architecture layers (docs/architecture.md#architecture)\ntype = layers\nlayers =\n'
  for i in $order; do
    local mod="${L_IMP[$i]}"
    case "$mod" in "$BASE".*) mod="${mod#"$BASE".}" ;; esac
    printf '    %s\n' "$mod"
  done
  printf 'containers =\n    %s\n' "$BASE"
  importlinter_ignores
  i=0
  while [ "$i" -lt "$f" ]; do
    li="$(idx_of "${F_LAYER[$i]}")"
    if [ -n "$li" ]; then
      printf '\n[importlinter:contract:forbidden-%s]\nname = Layer %s must not import %s (docs/architecture.md#architecture)\ntype = forbidden\n' "$((i + 1))" "${F_LAYER[$i]}" "${F_IMP[$i]}"
      printf 'source_modules =\n    %s\nforbidden_modules =\n    %s\n' "${L_IMP[$li]}" "${F_IMP[$i]}"
      importlinter_ignores
    fi
    i=$((i + 1))
  done
}

case "$target" in
  archunit-java) render_archunit java ;;
  archunit-kotlin) render_archunit kotlin ;;
  archunit-properties) printf '# %s\nfreeze.store.default.path=.agents/baselines/archunit\nfreeze.store.default.allowStoreCreation=true\n' "$GEN" ;;
  depcruise) render_depcruise ;;
  importlinter) render_importlinter ;;
esac
